const allArticles = rawArticles.filter(Boolean);

// Un post con publishedAt futuro queda cargado pero oculto hasta ese día (hora
// de Chile): no aparece en listados, su URL da 404 y el sitemap lo omite. Así
// se programan publicaciones sin redeploy.
// BLOG_TODAY=YYYY-MM-DD permite previsualizar en local cómo se verá el blog en
// otra fecha. En producción no se define.
export const todayInChile = () =>
  process.env.BLOG_TODAY ||
  new Intl.DateTimeFormat("en-CA", { timeZone: "America/Santiago" }).format(new Date());

export const isPublished = (article, today = todayInChile()) =>
  !article.publishedAt || article.publishedAt <= today;

export const getArticlesByLocale = (locale) => {
  const today = todayInChile();
  return allArticles.filter((a) => a.locale === locale && isPublished(a, today));
};
